create table if not exists freezers (
  id bigint generated by default as identity primary key,
  name text not null,
  created_at timestamptz not null default now()
);

create table if not exists locations (
  id bigint generated by default as identity primary key,
  freezer_id bigint not null references freezers(id) on delete cascade,
  name text not null,
  sort_order integer not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists items (
  id bigint generated by default as identity primary key,
  freezer_id bigint not null references freezers(id) on delete cascade,
  location_id bigint references locations(id) on delete set null,
  name text not null,
  category text,
  quantity numeric not null default 1,
  unit text not null default 'Stück',
  frozen_at date,
  best_before date,
  barcode text,
  image_url text,
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists shopping_list (
  id bigint generated by default as identity primary key,
  name text not null,
  quantity numeric not null default 1,
  unit text not null default 'Stück',
  checked boolean not null default false,
  source_item_id bigint references items(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists locations_freezer_idx on locations(freezer_id);
create index if not exists items_freezer_idx on items(freezer_id);
